#' tabshiftr: Reshape Disorganised Messy Data
#'
#' The tabshiftr package helps the user to build and register schema
#' descriptions of disorganised (messy) tables. Disorganised tables are tables
#' that are not in a topologically coherent form, where packages such as
#' \pkg{tidyr} could be used for reshaping. The schema description documents
#' the arrangement of input tables and is used to reshape them into a
#' standardised (tidy) output format.
#'
#' @author \strong{Maintainer, Author}: Steffen Ehrmann
#'   \email{steffen.ehrmann@posteo.de}
